// Есептің ұпайын жауаптарға бөлу (барлығы ресми ұпайға тең; self — өзін-өзі тексеру ұпайы).
function problem(base, n, pts, split) {
  const p = { ...base, n, pts };
  p.answers = base.answers.map((a) => ({ ...a, pts: a.ptsKey === 'all' ? pts : split[a.ptsKey] }));
  p.self = (base.self || []).map((s) => ({ ...s, pts: split[s.ptsKey] }));
  return p;
}

function round(g, problems) {
  const k = `2025-audan-${g}-t`;
  const img = IMG[k];
  const dir = `/img/olympiad/${k}`;
  return {
    k, g, kind: 'theory', year: '2025–2026', stage: 'Аудандық кезең', minutes: 120,
    title: 'Физикадан Республикалық олимпиаданың аудандық (қалалық) кезеңі, теориялық тур',
    problems: problems.map((p) => ({
      ...p,
      cond: { kk: img.c[p.n].kk, ru: img.c[p.n].ru },
      sol: img.s[p.n],
      dir,
    })),
  };
}

